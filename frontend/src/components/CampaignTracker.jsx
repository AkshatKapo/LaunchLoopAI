
/**
 * LaunchLoop AI - Campaign Tracker
 *
 * Allows restaurant owners to monitor the execution of their
 * saved AI-generated marketing campaigns.
 *
 * Features:
 * - Select and manage saved campaigns
 * - Track completed campaign tasks
 * - Calculate execution progress and campaign status
 * - Manually record campaign performance metrics
 * - Save performance results in browser localStorage
 *
 * This component does not make AI requests, launch advertisements,
 * or automatically retrieve performance data from external platforms.
 */

import { useState } from "react";
import {
  ClipboardList,
  CheckCircle2,
  ArrowRight,
  CalendarDays,
  BarChart3,
  Save
} from "lucide-react";

/**
 * Campaign Tracker component.
 *
 * @param {Array} campaigns - Saved marketing campaigns.
 * @param {Function} onTasksChange - Updates completed campaign tasks.
 * @param {Function} onOpenCampaign - Opens the selected campaign details.
 */
export default function CampaignTracker({
  campaigns = [],
  onTasksChange,
  onOpenCampaign
}) {

  // Store the ID of the campaign selected by the user.
  const [selectedId, setSelectedId] = useState("");

  /**
   * Load previously recorded campaign performance results.
   *
   * Performance metrics are stored separately from task progress
   * and organized by campaign ID.
   *
   * This initializer runs when the component is first mounted.
   */
  const [performanceByCampaign, setPerformanceByCampaign] = useState(() => {
    try {
      const stored = JSON.parse(
        localStorage.getItem("launchloop-performance-v1") || "{}"
      );

      return stored &&
        typeof stored === "object" &&
        !Array.isArray(stored)
          ? stored
          : {};
    } catch {
      // Fall back to empty results if stored data is unavailable
      // or cannot be parsed.
      return {};
    }
  });

  // Find the selected campaign.
  // Default to the first saved campaign if no selection exists.
  const selected =
    campaigns.find((campaign) => campaign.id === selectedId) ||
    campaigns[0];

  // Retrieve execution tasks from the selected campaign.
  const tasks = selected?.tasks || [];

  // Count how many campaign tasks have been completed.
  const completed = tasks.filter((task) => task.completed).length;

  // Calculate task completion percentage.
  // Use 0% when the campaign has no execution tasks.
  const percent = tasks.length
    ? Math.round((completed / tasks.length) * 100)
    : 0;

  // Determine the campaign's execution status.
  const status =
    tasks.length === 0 || completed === 0
      ? "Not Started"
      : completed === tasks.length
        ? "Completed"
        : "In Progress";

  /**
   * Retrieve the success metrics generated by NVIDIA Nemotron.
   *
   * These metrics represent suggested campaign KPIs.
   * Actual performance values are entered manually by the user.
   */
  const metricNames = Array.isArray(
    selected?.campaign?.strategy?.successMetrics
  )
    ? selected.campaign.strategy.successMetrics.filter(
        (name) => typeof name === "string"
      )
    : [];

  // Retrieve saved performance values for the selected campaign.
  const currentMetrics = selected
    ? (performanceByCampaign[selected.id] || {})
    : {};

  /**
   * Update a manually recorded performance metric.
   *
   * Updates the component state and saves results in localStorage
   * using the campaign ID and metric index.
   *
   * @param {number} index - Position of the metric.
   * @param {string} value - Performance value entered by the user.
   */
  function updateMetric(index, value) {
    if (!selected) return;

    // Preserve other campaigns' results while updating one metric.
    const next = {
      ...performanceByCampaign,
      [selected.id]: {
        ...currentMetrics,
        [index]: value
      },
    };

    // Immediately update the displayed metric value.
    setPerformanceByCampaign(next);

    try {
      // Persist performance results in the current browser.
      localStorage.setItem(
        "launchloop-performance-v1",
        JSON.stringify(next)
      );
    } catch {
      // The form still works if browser storage is unavailable or full.
    }
  }

  /**
   * Update the completion state of a campaign task.
   *
   * Creates an updated task list and passes it to the parent
   * component, which manages saved campaign task progress.
   *
   * @param {string} taskId - ID of the task being updated.
   * @param {boolean} checked - Whether the task is completed.
   */
  function toggleTask(taskId, checked) {
    if (!selected) return;

    onTasksChange(
      selected.id,
      tasks.map((task) =>
        task.id === taskId
          ? { ...task, completed: checked }
          : task
      )
    );
  }

  return (
    <div className="tracker-page">

      {/* Campaign Tracker page heading */}
      <div className="page-heading">
        <div className="eyebrow">
          <ClipboardList size={15} /> CAMPAIGN MANAGEMENT
        </div>

        <h1>Campaign Tracker</h1>

        <p>
          Follow your AI-generated execution plan and save your progress.
        </p>
      </div>

      {/* Show an empty state if no finalized campaigns exist */}
      {campaigns.length === 0 ? (
        <section className="panel tracker-empty">
          <ClipboardList size={32} />

          <h2>No campaigns to track yet</h2>

          <p>
            Finalize a marketing strategy in Campaign Studio
            to create its checklist.
          </p>
        </section>
      ) : (
        <div className="tracker-layout">

          {/* List of saved campaigns available for tracking */}
          <section className="panel tracker-campaign-list">
            <h2>Your Campaigns</h2>

            <p className="tracker-muted">
              Select a campaign to manage its progress.
            </p>

            {campaigns.map((item) => {

              // Calculate completed tasks for each campaign in the list.
              const total = item.tasks?.length || 0;
              const done = (item.tasks || []).filter(
                (task) => task.completed
              ).length;

              return (
                <button
                  type="button"
                  key={item.id}
                  className={`tracker-campaign-choice ${
                    selected?.id === item.id ? "selected" : ""
                  }`}
                  onClick={() => setSelectedId(item.id)}
                >
                  <strong>
                    {item.campaign?.selectedOption?.name ||
                      "Marketing Campaign"}
                  </strong>

                  <span>
                    {item.input?.restaurantName || "Restaurant"}
                    {" "}· {done}/{total} steps
                  </span>
                </button>
              );
            })}
          </section>

          {/* Detailed tracking information for the selected campaign */}
          <section className="panel tracker-details">

            {/* Selected campaign overview and current status */}
            <div className="tracker-details-heading">
              <div>
                <p className="tracker-kicker">
                  CAMPAIGN OVERVIEW
                </p>

                <h2>
                  {selected?.campaign?.selectedOption?.name ||
                    "Marketing Campaign"}
                </h2>

                <p className="tracker-muted">
                  {selected?.input?.restaurantName}
                  {" "}· {selected?.input?.location}
                </p>
              </div>

              <span className="tracker-status">
                {status}
              </span>
            </div>

            {/* Summary of campaign task completion */}
            <div className="tracker-stats">
              <div>
                <span>Progress</span>
                <strong>{percent}%</strong>
              </div>

              <div>
                <span>Tasks completed</span>
                <strong>
                  {completed}/{tasks.length}
                </strong>
              </div>

              <div>
                <span>Campaign status</span>
                <strong className="tracker-stat-status">
                  {status}
                </strong>
              </div>
            </div>

            {/* Visual progress bar showing execution completion */}
            <div className="tracker-progress-heading">
              <strong>Execution progress</strong>
              <span>{percent}%</span>
            </div>

            <div
              className="tracker-progress-track"
              role="progressbar"
              aria-label="Campaign completion"
              aria-valuemin={0}
              aria-valuemax={100}
              aria-valuenow={percent}
            >
              <div
                className="tracker-progress-fill"
                style={{ width: `${percent}%` }}
              />
            </div>

            {/* Execution checklist generated from the campaign timeline */}
            <h3 className="tracker-checklist-title">
              <CalendarDays size={18} />
              Execution Checklist
            </h3>

            {tasks.length ? (
              tasks.map((task) => (
                <label
                  className={`tracker-task ${
                    task.completed ? "completed" : ""
                  }`}
                  key={task.id}
                >
                  {/* Manually mark a campaign execution step as complete */}
                  <input
                    type="checkbox"
                    checked={Boolean(task.completed)}
                    onChange={(event) =>
                      toggleTask(task.id, event.target.checked)
                    }
                  />

                  <span className="tracker-task-content">
                    <strong>{task.phase}</strong>
                    <span>{task.action}</span>
                  </span>

                  {/* Completion icon shown for finished tasks */}
                  {task.completed && (
                    <CheckCircle2
                      size={20}
                      className="tracker-check-icon"
                    />
                  )}
                </label>
              ))
            ) : (
              <p className="tracker-muted">
                This campaign has no timeline tasks.
                Generate a campaign with a timeline to track its progress.
              </p>
            )}

            {/* Manual campaign performance recording */}
            <section className="tracker-performance">
              <h3>
                <BarChart3 size={18} />
                Campaign Performance
              </h3>

              <p className="tracker-muted">
                Enter your real campaign results below.
                These are manually recorded values,
                not automatically verified by advertising platforms.
              </p>

              {/* Create one input field for each AI-suggested KPI */}
              {metricNames.length > 0 ? (
                <div className="tracker-metric-grid">
                  {metricNames.map((name, index) => (
                    <label
                      className="tracker-metric-field"
                      key={`${index}-${name}`}
                    >
                      <span>{name}</span>

                      <input
                        type="text"
                        inputMode="decimal"
                        maxLength={80}
                        placeholder="e.g. 120, 3.2%, $50"
                        value={currentMetrics[index] ?? ""}
                        onChange={(event) =>
                          updateMetric(index, event.target.value)
                        }
                      />
                    </label>
                  ))}
                </div>
              ) : (
                <p className="tracker-muted">
                  No suggested metrics were generated for this campaign.
                </p>
              )}

              {/* Inform users that metric values are saved automatically */}
              <p className="tracker-save-note">
                <Save size={14} />
                Results are saved automatically in this browser.
              </p>
            </section>

            {/* Navigate to the full saved campaign */}
            <button
              type="button"
              className="tracker-open-button"
              onClick={() => onOpenCampaign(selected.id)}
            >
              View Campaign Details
              <ArrowRight size={17} />
            </button>

            {/* Clarify that progress and metrics are manually recorded */}
            <p className="tracker-disclaimer">
              Progress is manually updated and saved in this browser.
              It does not launch ads or verify campaign results.
            </p>
          </section>
        </div>
      )}
    </div>
  );
}
